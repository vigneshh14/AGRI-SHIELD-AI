#!/usr/bin/env python3
"""Automated cross-artifact consistency audit. Exit 1 on any disagreement."""
import json, re, glob, pathlib, sys

m=json.load(open("runs/tomato4_scratch/metrics.json")); e=json.load(open("reports/external_plantdoc.json"))
a=json.load(open("reports/audit.json")); s=json.load(open("datasets/metadata/split_summary.json"))
t=m["test_metrics"]; p3=e["primary_protocol_3class"]
RETRACTED={"0.9615":"superseded accuracy","0.9563":"superseded macro F1","96.15":"superseded accuracy"}
CONTEXT=("retract","supersede","earlier","audit caught","previous","historical",
         "corrected","final-epoch","obsolete","do not use","wrong")
SKIP=("CONSISTENCY_AUDIT","VERIFICATION_REPORT","FILE_MANIFEST","PHASE1_REPORT1","OBSOLETE")
docs=[f for f in glob.glob("*.md") if not f.startswith(SKIP)]
fails=[]

for f in sorted(docs):
    lines=pathlib.Path(f).read_text(encoding="utf-8").splitlines()
    for i,line in enumerate(lines):
        for pat,name in RETRACTED.items():
            if pat not in line: continue
            window=" ".join(lines[max(0,i-2):i+3]).lower()   # +/- 2 lines of context
            if not any(w in window for w in CONTEXT):
                fails.append(f"{f}:{i+1} retracted {name} '{pat}' uncontextualised :: {line.strip()[:70]}")

rep=pathlib.Path("PHASE1_REPORT.md").read_text(encoding="utf-8")
res=pathlib.Path("PHASE1_RESULTS.md").read_text(encoding="utf-8")

checks=[
 ("report carries in-domain accuracy",      f"{t['accuracy']:.4f}" in rep),
 ("results carries in-domain accuracy",     f"{t['accuracy']:.7f}" in res),
 ("report carries PlantDoc primary acc",    f"{p3['accuracy']:.4f}" in rep),
 ("results carries PlantDoc primary acc",   f"{p3['accuracy']:.4f}" in res),
 ("report carries sensitivity acc",         f"{e['metrics']['accuracy']:.4f}" in rep),
 ("report carries leakage %",               str(s['naive_test_contamination_pct']) in rep),
 ("report carries lower-bound caveat",      "lower bound" in rep.lower()),
 ("report carries pte size",                str(a['pte_mb']) in rep),
 ("report carries logit tolerance",         f"{a['pte_vs_pytorch_max_logit_diff']:.3e}" in rep),
 ("report carries confusion diagonal",      all(str(m['test_confusion_matrix'][i][i]) in rep for i in range(4))),
 ("report carries correct-prediction count",str(sum(m['test_confusion_matrix'][i][i] for i in range(4))) in rep),
 ("report carries ungrouped count",         str(s['grouping_coverage']['ungrouped']) in rep),
 ("report carries AUC 0.963",               "0.963" in rep),
 ("severity marked EXPERIMENTAL",           "EXPERIMENTAL" in rep),
 ("severity background unresolved stated",  "background sensitivity remains unresolved" in rep.lower()),
 ("Arm figures stated as none",             "NONE EXIST" in rep or "no `[ARM]` figure exists" in rep.lower()),
 ("mock does not satisfy Llama stated",     "mock backend does not satisfy" in rep.lower()),
]
rd=pathlib.Path("README.md").read_text(encoding="utf-8")
ua=pathlib.Path("USER_ACTIONS.md").read_text(encoding="utf-8")
pp=pathlib.Path("PROJECT_PROGRESS.md").read_text(encoding="utf-8")
checks += [
 ("README: no claim Llama runs on device",
  not re.search(r"advisory text is generated by \*\*Llama", rd, re.I)
  and "never been executed" in rd.lower()),
 ("README: Arm deployment stated pending", "arm / android deployment" in rd.lower() or "Arm deployment" in rd),
 ("README: implemented vs planned separated",
  "## Implemented and verified" in rd and "## Planned — NOT implemented" in rd),
 ("README: leaf-ID grouping described", "human-annotated leaf identities" in rd.lower()
  or "human-annotated leaf map" in rd.lower()),
 ("README: abstain reason stated", "0 source-verified chemical interventions" in rd),
 ("README: no false 'every chemical traces to a source' claim",
  "Every chemical name, dose and interval\ntraces to a named source" not in rd),
 ("USER_ACTIONS: completed Windows audit moved out of blockers",
  "Approve computer use so the Windows audit can run" not in ua
  and "Completed — no longer needs you" in ua),
 ("USER_ACTIONS: Git/adb status dated", "30 Oct 2026 20:53" in ua),
 ("PROJECT_PROGRESS labelled historical", "HISTORICAL SESSION LOG" in pp
  and "historical entry" in pp),
]
bad_llama=[l for l in rep.splitlines()
           if re.search(r"llama.{0,60}(is deployed|was deployed|running on|executed on)", l, re.I)
           and not re.search(r"\bnot\b|never|pending", l, re.I)]
checks.append(("no sentence implies Llama was deployed", not bad_llama))

for name,ok in checks:
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    if not ok: fails.append(name)

print()
if fails:
    print("CONSISTENCY FAILURES:")
    for x in fails: print("  -",x)
    sys.exit(1)
print("CONSISTENCY AUDIT PASSED — every document agrees with the authoritative JSON")
