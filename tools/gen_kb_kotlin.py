#!/usr/bin/env python3
"""Generate android/advisory/KnowledgeBase.kt from knowledge_base/tomato_tnau_v2.json.

The JSON is the single source of truth. Never hand-edit KnowledgeBase.kt;
edit the JSON and re-run:  python tools/gen_kb_kotlin.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "knowledge_base" / "tomato_tnau_v2.json"
OUT = ROOT / "android" / "advisory" / "KnowledgeBase.kt"


def s(v):
    if v is None:
        return "null"
    return json.dumps(v, ensure_ascii=False).replace("$", "\\$")


def lst(items):
    return "listOf(" + ", ".join(s(x) for x in items) + ")"


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    recs = []
    for r in d["records"]:
        chems = ", ".join(f"Chemical({s(c['active'])}, {s(c['dose'])})" for c in r["chemicals"])
        bios = ", ".join(
            f"Biological({s(b['agent'])}, {s(b['use'])}, {s(b['dose'])})" for b in r["biological"]
        )
        if r["chemicals"] and (not r["sourced"] or not r["source_url"]):
            sys.exit(f"REFUSING: {r['id']} has chemicals but no verified source")
        recs.append(
            "        KbRecord(\n"
            f"            id = {s(r['id'])},\n"
            f"            classLabel = {s(r['class_label'])},\n"
            f"            crop = {s(r['crop'])}, cropTa = {s(r['crop_ta'])},\n"
            f"            disease = {s(r['disease'])}, diseaseTa = {s(r['disease_ta'])},\n"
            f"            pathogen = {s(r['pathogen'])},\n"
            f"            symptomsEn = {lst(r['symptoms_en'])},\n"
            f"            culturalEn = {lst(r['cultural_en'])},\n"
            f"            biological = listOf({bios}),\n"
            f"            chemicals = listOf({chems}),\n"
            f"            chemicalNote = {s(r.get('chemical_choice_note'))},\n"
            f"            sourced = {str(r['sourced']).lower()},\n"
            f"            sourceInstitution = {s(r['source_institution'])},\n"
            f"            sourceUrl = {s(r['source_url'])},\n"
            f"            verifiedOn = {s(r['verified_on'])},\n"
            "        )"
        )
    body = (
        "// GENERATED by tools/gen_kb_kotlin.py from knowledge_base/tomato_tnau_v2.json.\n"
        "// Do not edit by hand.\n"
        "package com.agrishield.advisory\n\n"
        "object KnowledgeBase {\n"
        f"    const val GENERATED_FROM = {s(SRC.name)}\n"
        f"    const val SCHEMA_VERSION = {s(d['schema_version'])}\n\n"
        "    val records: List<KbRecord> = listOf(\n" + ",\n".join(recs) + ",\n    )\n\n"
        "    fun byClassLabel(label: String): KbRecord? = records.firstOrNull { it.classLabel == label }\n"
        "}\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(recs)} records")


if __name__ == "__main__":
    main()
